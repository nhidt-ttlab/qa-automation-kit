/**
 * Backfills the ERP Feature List id onto historical test_cases rows.
 *
 *   pnpm db:backfill-feature-id -- --dry-run     # report only, writes nothing
 *   pnpm db:backfill-feature-id                  # apply
 *
 * **Why a separate script rather than a smarter `db:sync`.** `db:sync` pass 1 iterates
 * `SELECT * FROM test_cases` on the runner's SQLite file, so it can only ever visit the scenarios
 * that database still holds. The runner's SQLite is a working file that gets rotated; Postgres is
 * the archive. Every scenario whose rows have aged out of SQLite is therefore invisible to the
 * sync forever, and no amount of re-running `db:sync` will give it a `feature_id`.
 *
 * This is the counterpart to `backfill-check-csv-metadata.ts`, and it differs from that script in
 * one important way: `feature_id` is **not** a run-time snapshot. It is a property of the scenario
 * as it is declared in source today, so re-deriving it now is correct rather than a falsification.
 * That is why this script reads the registry directly and why it may safely fill a row whose run
 * predates the column.
 *
 * **What counts as an establishable mapping.** Exactly one thing, and it is not a guess: the
 * scenario's own `const FEATURE_ID`, as captured in the runner's
 * `src/harness/registry/names/scenario-groups.generated.ts`. That file is generated by
 * `tools/maintenance/generate-scenario-groups.ts` and guarded against drift by
 * `src/harness/fitness/scenario-groups.test.ts`, so it is the same value the runner itself would
 * have written. A scenario absent from the registry, or present but declaring no `FEATURE_ID`, is
 * reported as unresolved and left alone. A feature id is never inferred from a sibling scenario,
 * from the module, or from the testcase id prefix.
 *
 * Safe to interrupt and rerun: a row is written only when `feature_id` is still NULL, so a second
 * pass writes nothing and changes nothing. It never overwrites a value the runner wrote, never
 * deletes a row, and touches no column other than `feature_id`.
 *
 * Flags:
 *   --dry-run          compute and report; opens no transaction and performs no write
 *   --batch-size=N     test_cases per transaction (default 500)
 *   --limit=N          only the N oldest candidate rows — for a quick smoke test
 *   --samples=N        how many representative samples to print (default 5)
 *   --runner=PATH      the regression runner package (default: REGRESSION_RUNNER_PATH)
 */
import '../src/common/load-reporting-env';
import * as fs from 'fs';
import * as path from 'path';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '../src/generated/prisma/client';
import { resolveArtifactStorageRoot } from '../src/modules/runs/artifact-storage.util';

function numericFlag(name: string, fallback: number): number {
  const raw = process.argv.find((a) => a.startsWith(`--${name}=`));
  if (!raw) return fallback;
  const value = Number.parseInt(raw.slice(name.length + 3), 10);
  return Number.isFinite(value) && value > 0 ? value : fallback;
}

function stringFlag(name: string): string | undefined {
  const raw = process.argv.find((a) => a.startsWith(`--${name}=`));
  return raw ? raw.slice(name.length + 3) : undefined;
}

/** One parsed registry line: every scenario the runner knows, with its feature id when declared. */
interface RegistryEntry {
  featureId?: string;
}

/**
 * Reads `SCENARIO_GROUPS` out of the generated module.
 *
 * A line parse rather than an import: this is a NestJS/CommonJS script in a different package from
 * the runner's ESM `#harness/*` subpath imports, and pulling that module in would drag the whole
 * registry's type graph across a package boundary for one field.
 *
 * The renderer (`renderScenarioGroupsModule`) emits exactly one scenario per line in a fixed,
 * single-quoted shape, so the parse is deterministic. It is still verified rather than trusted: the
 * number of entry-shaped lines must equal the number of lines inside the object literal, or the
 * file has changed shape and this script must be updated instead of silently reading half of it.
 */
function loadRegistry(runnerPath: string): Map<string, RegistryEntry> {
  const file = path.join(
    runnerPath,
    'src',
    'harness',
    'registry',
    'names',
    'scenario-groups.generated.ts',
  );
  if (!fs.existsSync(file)) {
    throw new Error(
      `No scenario registry at ${file}. Run \`npx tsx tools/maintenance/generate-scenario-groups.ts\` ` +
        'in the regression runner first, or pass --runner=<path>.',
    );
  }
  const source = fs.readFileSync(file, 'utf8');

  const open = source.indexOf('SCENARIO_GROUPS: Record<string, ScenarioGroup> = {');
  if (open === -1) throw new Error(`${file} has no SCENARIO_GROUPS object literal.`);
  const close = source.indexOf('\n};', open);
  if (close === -1) throw new Error(`${file}: SCENARIO_GROUPS is not terminated.`);
  const body = source.slice(source.indexOf('\n', open) + 1, close);

  const bodyLines = body.split('\n').filter((l) => l.trim().length > 0);
  const entries = new Map<string, RegistryEntry>();
  for (const line of bodyLines) {
    const key = line.match(/^\s*'([^']+)'\s*:\s*\{/);
    if (!key) continue;
    const featureId = line.match(/\bfeatureId:\s*'([^']+)'/)?.[1];
    entries.set(key[1], featureId ? { featureId } : {});
  }
  if (entries.size !== bodyLines.length) {
    throw new Error(
      `${file}: parsed ${entries.size} scenarios from ${bodyLines.length} lines. The generated ` +
        'file has changed shape — update loadRegistry rather than backfilling from a partial read.',
    );
  }
  return entries;
}

type Unresolved = { scenarioKey: string; reason: string };

async function main(): Promise<void> {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) throw new Error('DATABASE_URL is not set.');

  const dryRun = process.argv.includes('--dry-run');
  const batchSize = numericFlag('batch-size', 500);
  const limit = process.argv.some((a) => a.startsWith('--limit=')) ? numericFlag('limit', 0) : undefined;
  const sampleCount = numericFlag('samples', 5);
  const runnerPath = stringFlag('runner') ?? resolveArtifactStorageRoot();

  const startedAt = Date.now();
  const registry = loadRegistry(runnerPath);
  const declared = [...registry.values()].filter((e) => e.featureId).length;

  console.log(`Source (runner):   ${runnerPath}`);
  console.log(`Target (Postgres): ${connectionString.replace(/:[^:@/]*@/, ':***@')}`);
  console.log(`Mode:              ${dryRun ? 'DRY RUN — no writes' : 'APPLY'}`);
  if (limit) console.log(`Limit:             ${limit} oldest candidate rows`);
  console.log(`Backfilled on:     ${new Date().toISOString()}`);
  console.log(`Registry:          ${registry.size} scenarios, ${declared} declaring a FEATURE_ID`);
  console.log('');

  const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString }) });
  const unresolved: Unresolved[] = [];
  const samples: string[] = [];
  let resolved = 0;
  let written = 0;

  try {
    // Only rows still entirely unfilled. This is the idempotency guarantee, and it is also what
    // stops a rerun from overwriting a value the runner itself wrote through db:sync.
    const candidates = await prisma.testCase.findMany({
      where: { featureId: null },
      select: { id: true, scenarioKey: true },
      orderBy: { createdAt: 'asc' },
      ...(limit ? { take: limit } : {}),
    });
    console.log(`Candidate test_cases: ${candidates.length}`);

    let pending: Array<{ id: string; featureId: string }> = [];
    const flush = async (): Promise<void> => {
      if (dryRun || pending.length === 0) {
        pending = [];
        return;
      }
      await prisma.$transaction(
        pending.map((u) =>
          prisma.testCase.update({ where: { id: u.id }, data: { featureId: u.featureId } }),
        ),
      );
      written += pending.length;
      pending = [];
    };

    for (const tc of candidates) {
      const entry = registry.get(tc.scenarioKey);
      if (!entry) {
        unresolved.push({
          scenarioKey: tc.scenarioKey,
          reason: 'scenario is not in the runner registry (renamed or deleted)',
        });
        continue;
      }
      if (!entry.featureId) {
        unresolved.push({
          scenarioKey: tc.scenarioKey,
          reason: 'scenario declares no FEATURE_ID',
        });
        continue;
      }

      resolved += 1;
      if (samples.length < sampleCount) {
        samples.push(`  ${tc.scenarioKey} -> ${entry.featureId}`);
      }
      pending.push({ id: tc.id, featureId: entry.featureId });
      if (pending.length >= batchSize) await flush();
    }
    await flush();

    console.log(`\nResolved to a declared FEATURE_ID:  ${resolved}`);
    console.log(`Unresolved (left untouched):        ${unresolved.length}`);
    console.log(`Rows written:                       ${written}${dryRun ? ' (dry run)' : ''}`);

    if (samples.length) {
      console.log('\nSamples:');
      for (const s of samples) console.log(s);
    }

    if (unresolved.length) {
      const byReason = new Map<string, number>();
      for (const u of unresolved) byReason.set(u.reason, (byReason.get(u.reason) ?? 0) + 1);
      console.log('\nUnresolved mappings — reported, never guessed:');
      for (const [reason, count] of [...byReason.entries()].sort((a, b) => b[1] - a[1])) {
        console.log(`  ${String(count).padStart(5)}  ${reason}`);
      }
      for (const u of unresolved.slice(0, sampleCount)) {
        console.log(`    e.g. ${u.scenarioKey}`);
      }
    }

    if (dryRun) {
      // A dry run that wrote something would be a bug worth failing on, not a warning to skim.
      if (written !== 0) throw new Error(`Dry run wrote ${written} rows — refusing to report success.`);
      console.log('\nDry run wrote nothing, as expected.');
    } else {
      console.log('\nBackfill complete.');
    }
    console.log(`Elapsed: ${((Date.now() - startedAt) / 1000).toFixed(1)}s`);
  } finally {
    await prisma.$disconnect();
  }
}

// Only run when invoked as a script, so the pure helpers above stay unit-testable.
if (require.main === module) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
}
